// Generates TinyGo target JSON and gba-smoke.s from TinyGo's GBA target
// plus this repo's gba.ld / gba.s.
//
// extra-files must be TINYGOROOT-relative (filepath.Rel): TinyGo resolves
// each entry against its install root. Rel paths that walk out of
// the TinyGo install (../../../../home/...) are still relative, but
// machine-local; the JSON is generated and gitignored. linkerscript is
// absolute by design.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const zeroMarker = "// MTILE_ZERO_EWRAM\n"

const poisonBlock = `    // MTILE_POISON_EWRAM (generated; do not edit)
    ldr     r0, =_ewram_start
    ldr     r1, =_ewram_end
    ldr     r2, =0xF1F1F1F1
.Lpoison_ewram:
    cmp     r0, r1
    bhs     .Lpoison_ewram_done
    str     r2, [r0], #4
    b       .Lpoison_ewram
.Lpoison_ewram_done:

`

const poisonImmediate = "0xF1F1F1F1"

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "gentarget: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	runtimeDir, err := os.Getwd()
	if err != nil {
		return err
	}
	tinygoRoot := os.Getenv("TINYGOROOT")
	if tinygoRoot == "" {
		out, err := exec.Command("tinygo", "env", "TINYGOROOT").Output()
		if err != nil {
			return fmt.Errorf("tinygo env TINYGOROOT: %w", err)
		}
		tinygoRoot = strings.TrimSpace(string(out))
	}
	tinygoRoot, err = filepath.Abs(tinygoRoot)
	if err != nil {
		return err
	}

	srcJSON := filepath.Join(tinygoRoot, "targets", "gameboy-advance.json")
	raw, err := os.ReadFile(srcJSON)
	if err != nil {
		return err
	}
	var spec map[string]any
	if err := json.Unmarshal(raw, &spec); err != nil {
		return fmt.Errorf("parse %s: %w", srcJSON, err)
	}

	gbaS, err := filepath.Abs(filepath.Join(runtimeDir, "crt0", "gba.s"))
	if err != nil {
		return err
	}
	gbaSmokeS, err := filepath.Abs(filepath.Join(runtimeDir, "crt0", "gba-smoke.s"))
	if err != nil {
		return err
	}
	ldPath, err := filepath.Abs(filepath.Join(runtimeDir, "crt0", "gba.ld"))
	if err != nil {
		return err
	}
	if _, err := os.Stat(ldPath); err != nil {
		return fmt.Errorf("linkerscript: %w", err)
	}

	asm, err := os.ReadFile(gbaS)
	if err != nil {
		return err
	}
	if !bytes.Contains(asm, []byte(zeroMarker)) {
		return fmt.Errorf("%s: missing %q marker", gbaS, strings.TrimSpace(zeroMarker))
	}
	if bytes.Contains(asm, []byte("MTILE_POISON_EWRAM")) {
		return fmt.Errorf("%s: production crt0 must not contain the smoke poison marker", gbaS)
	}
	if hasPoisonImmediate(asm) {
		return fmt.Errorf("%s: production crt0 must not contain the smoke poison immediate", gbaS)
	}
	generated := bytes.Replace(asm, []byte(zeroMarker), []byte(poisonBlock+zeroMarker), 1)
	header := []byte("// Code generated by go run ./internal/cmd/gentarget. DO NOT EDIT.\n")
	if err := os.WriteFile(gbaSmokeS, append(header, generated...), 0o644); err != nil {
		return err
	}

	relS, err := tinygoRel(tinygoRoot, gbaS)
	if err != nil {
		return fmt.Errorf("gba.s extra-files: %w", err)
	}
	relSmoke, err := tinygoRel(tinygoRoot, gbaSmokeS)
	if err != nil {
		return fmt.Errorf("gba-smoke.s extra-files: %w", err)
	}
	asmArm := filepath.Join(tinygoRoot, "src", "runtime", "asm_arm.S")
	if _, err := os.Stat(asmArm); err != nil {
		return fmt.Errorf("tinygo asm_arm.S: %w", err)
	}

	spec["gc"] = "none"
	spec["linkerscript"] = ldPath

	if err := writeTarget(spec, []string{relS, "src/runtime/asm_arm.S"}, filepath.Join(runtimeDir, "target-gba.json")); err != nil {
		return err
	}
	return writeTarget(spec, []string{relSmoke, "src/runtime/asm_arm.S"}, filepath.Join(runtimeDir, "target-gba-smoke.json"))
}

// tinygoRel returns a TINYGOROOT-relative extra-files path. TinyGo compiles
// extra-files as Join(TINYGOROOT, path), so the result must not be absolute.
func tinygoRel(tinygoRoot, absFile string) (string, error) {
	if !filepath.IsAbs(absFile) {
		return "", fmt.Errorf("need absolute path, got %q", absFile)
	}
	rel, err := filepath.Rel(tinygoRoot, absFile)
	if err != nil {
		return "", err
	}
	if filepath.IsAbs(rel) {
		return "", fmt.Errorf("extra-files path must be TINYGOROOT-relative, got %q", rel)
	}
	joined := filepath.Clean(filepath.Join(tinygoRoot, rel))
	if _, err := os.Stat(joined); err != nil {
		return "", fmt.Errorf("Join(TINYGOROOT, %q) does not exist: %w", rel, err)
	}
	want, err := filepath.EvalSymlinks(absFile)
	if err != nil {
		return "", err
	}
	got, err := filepath.EvalSymlinks(joined)
	if err != nil {
		return "", err
	}
	if got != want {
		return "", fmt.Errorf("Join(TINYGOROOT, %q) = %s, want %s", rel, got, want)
	}
	return rel, nil
}

// hasPoisonImmediate reports whether src contains the smoke poison constant in
// an instruction or data operand. Line comments (// and @) are ignored.
func hasPoisonImmediate(src []byte) bool {
	needle := []byte(poisonImmediate)
	lower := []byte(strings.ToLower(poisonImmediate))
	for _, line := range bytes.Split(src, []byte("\n")) {
		if i := bytes.Index(line, []byte("//")); i >= 0 {
			line = line[:i]
		}
		if i := bytes.Index(line, []byte("@")); i >= 0 {
			line = line[:i]
		}
		if bytes.Contains(bytes.ToLower(line), lower) || bytes.Contains(line, needle) {
			return true
		}
	}
	return false
}

func writeTarget(base map[string]any, extraFiles []string, dest string) error {
	for _, f := range extraFiles {
		if filepath.IsAbs(f) {
			return fmt.Errorf("%s: extra-files must be TINYGOROOT-relative, got %q", dest, f)
		}
	}
	spec := cloneMap(base)
	files := make([]any, len(extraFiles))
	for i, f := range extraFiles {
		files[i] = f
	}
	spec["extra-files"] = files
	buf, err := json.MarshalIndent(spec, "", "\t")
	if err != nil {
		return err
	}
	buf = append(buf, '\n')
	return os.WriteFile(dest, buf, 0o644)
}

func cloneMap(src map[string]any) map[string]any {
	dst := make(map[string]any, len(src))
	for k, v := range src {
		dst[k] = v
	}
	return dst
}
