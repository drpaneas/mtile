//go:build discordtrial

package main

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"

	"github.com/drpaneas/mtile/internal/build"
	"github.com/drpaneas/mtile/internal/transpiler"
)

func TestDiscordSharedAnimationTrial(t *testing.T) {
	repo, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	root := os.Getenv("MTILE_DISCORD_TRIAL_DIR")
	if root == "" {
		t.Skip("set MTILE_DISCORD_TRIAL_DIR to fixtures generated by scripts/discord-hardware/fixtures.py")
	}
	root, err = filepath.Abs(root)
	if err != nil {
		t.Fatal(err)
	}
	helper := filepath.Join(repo, "build/player/mtile-player")
	service, err := build.NewService("", "")
	if err != nil {
		t.Fatal(err)
	}
	service.Debug = true
	type item struct {
		Result    rendererResult `json:"result"`
		Frames    []uint32       `json:"frames"`
		Different int            `json:"differentFromSprites"`
	}
	results := map[string]item{}
	var baseline, shared *capture
	for _, kind := range []string{"sprites", "shared", "phases"} {
		out := filepath.Join(root, "animation-"+kind+"-capture")
		if err := os.MkdirAll(out, 0755); err != nil {
			t.Fatal(err)
		}
		project := filepath.Join(root, "animation-"+kind)
		var result build.Result
		var captured capture
		if baseline == nil {
			result, captured, err = buildAndCapture(service, transpiler.RendererMode0, project, helper, out, 0, 120)
		} else {
			result, captured, err = buildAndCaptureAtFrames(service, transpiler.RendererMode0, project, helper, out, 0, 120, baseline.frameNumbers)
		}
		if err != nil {
			t.Fatal(err)
		}
		pngPath := filepath.Join(out, "final.png")
		if err = writePNG(pngPath, captured.lastRGB); err != nil {
			t.Fatal(err)
		}
		summary, e := summarize(result, captured, pngPath)
		if e != nil {
			t.Fatal(e)
		}
		diff := 0
		if baseline == nil {
			baseline = &captured
		} else {
			diff = compareFrames(baseline.frames, captured.frames)
		}
		if kind == "shared" {
			shared = &captured
			if diff != 0 {
				t.Fatalf("shared animation differs by %d pixels", diff)
			}
		}
		if kind == "phases" {
			diff = compareFrames(shared.frames, captured.frames)
			if diff == 0 {
				t.Fatal("independent phase counterexample unexpectedly identical")
			}
		}
		results[kind] = item{summary, captured.frameNumbers, diff}
		t.Logf("%s median=%d p95=%d draw=%d commit=%d cold=%d rom=%d ewram_free=%d oam=%d line=%d missed=%d diff=%d", kind, summary.MedianCycles, summary.P95Cycles, summary.MedianDraw, summary.MedianCommit, summary.ColdUpload, summary.ROMBytes, summary.EWRAMFree, summary.OAMEntries, summary.OBJLineCycles, summary.MissedFrames, diff)
	}
	data, err := json.MarshalIndent(results, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(filepath.Join(root, "shared-animation-report.json"), append(data, '\n'), 0644); err != nil {
		t.Fatal(err)
	}
}
