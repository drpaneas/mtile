package build

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"

	"github.com/drpaneas/mtile/internal/assetsync"
)

type NewProjectOptions struct {
	SheetWidth  int
	SheetHeight int
	MapWidth    int
	MapHeight   int
}

func (o NewProjectOptions) withDefaults() NewProjectOptions {
	if o.SheetWidth == 0 {
		o.SheetWidth = 240
	}
	if o.SheetHeight == 0 {
		o.SheetHeight = 160
	}
	return o
}

func spriteCount(width, height int) int {
	return (width / 8) * (height / 8)
}

func validateNewProjectFootprint(sheetWidth, sheetHeight, mapWidth, mapHeight, spriteN int) error {
	sheetBytes := uint64(sheetWidth) * uint64(sheetHeight)
	mapBytes := uint64(mapWidth) * uint64(mapHeight) * 2
	assetBytes := sheetBytes
	var err error
	for _, item := range []struct {
		name  string
		bytes uint64
	}{
		{name: "map", bytes: mapBytes},
		{name: "flags", bytes: uint64(spriteN)},
		{name: "palette", bytes: 256 * 2},
	} {
		assetBytes, err = addAssetBytes(assetBytes, item.bytes, item.name)
		if err != nil {
			return err
		}
	}
	if assetBytes > uint64(maxGBAROMSize-gbaHeaderSize) {
		return fmt.Errorf("project asset payload exceeds the 32 MiB GBA cartridge capacity")
	}
	return nil
}

// CreateProject makes a native project with a full native-sized default sheet
// and map. It refuses to reuse an existing directory so a failed or repeated
// `new` command cannot silently overwrite artwork.
func CreateProject(projectDir string, options NewProjectOptions) error {
	options = options.withDefaults()
	if options.SheetWidth < 1 || options.SheetHeight < 1 {
		return errors.New("project dimensions must be positive")
	}
	maxInt := int(^uint(0) >> 1)
	if options.SheetWidth > maxInt/options.SheetHeight {
		return errors.New("project dimensions overflow host address space")
	}
	spriteN := spriteCount(options.SheetWidth, options.SheetHeight)
	mapWidth, mapHeight := options.MapWidth, options.MapHeight
	if spriteN == 0 {
		if mapWidth != 0 || mapHeight != 0 {
			return errors.New("a sheet with no complete 8x8 sprite cannot include a tile map")
		}
	} else {
		if mapWidth == 0 {
			mapWidth = 30
		}
		if mapHeight == 0 {
			mapHeight = 20
		}
		if mapWidth < 1 || mapHeight < 1 {
			return errors.New("project dimensions must be positive")
		}
		if mapWidth > maxInt/mapHeight {
			return errors.New("project dimensions overflow host address space")
		}
	}
	options.MapWidth, options.MapHeight = mapWidth, mapHeight
	if err := validateNewProjectFootprint(options.SheetWidth, options.SheetHeight, mapWidth, mapHeight, spriteN); err != nil {
		return err
	}
	projectDir, err := filepath.Abs(projectDir)
	if err != nil {
		return err
	}
	if _, err := os.Lstat(projectDir); err == nil {
		return fmt.Errorf("project directory %q already exists", projectDir)
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	parent := filepath.Dir(projectDir)
	if err := os.MkdirAll(parent, 0o755); err != nil {
		return fmt.Errorf("create project parent: %w", err)
	}
	tmp, err := os.MkdirTemp(parent, ".mtile-new-*")
	if err != nil {
		return fmt.Errorf("create project staging directory: %w", err)
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	if err := os.MkdirAll(filepath.Join(tmp, "assets", "palettes"), 0o755); err != nil {
		return err
	}
	if err := assetsync.SaveProject(tmp, assetsync.Project{
		ActivePalette: assetsync.CanonicalPaletteName,
		Renderer:      assetsync.DefaultRendererName,
	}); err != nil {
		return fmt.Errorf("write project.json: %w", err)
	}
	sheet := &assetsync.Spritesheet{Width: options.SheetWidth, Height: options.SheetHeight}
	if err := assetsync.SaveSpritesheet(tmp, sheet); err != nil {
		return fmt.Errorf("write spritesheet: %w", err)
	}
	mapData := &assetsync.Map{Width: options.MapWidth, Height: options.MapHeight, Cells: make([]int, options.MapWidth*options.MapHeight)}
	if err := assetsync.SaveMap(tmp, mapData); err != nil {
		return fmt.Errorf("write map: %w", err)
	}
	settings := assetsync.DefaultNativeAudioSettings()
	if err := assetsync.SaveNativeAudioSettings(tmp, &settings); err != nil {
		return fmt.Errorf("write audio settings: %w", err)
	}
	sounds := assetsync.DefaultNativeSoundLibrary()
	if err := assetsync.SaveNativeSounds(tmp, &sounds); err != nil {
		return fmt.Errorf("write audio sounds library: %w", err)
	}
	music := assetsync.DefaultNativeMusicLibrary()
	if err := assetsync.SaveNativeMusic(tmp, sounds, &music); err != nil {
		return fmt.Errorf("write audio music library: %w", err)
	}
	game := `-- Generated by mtile new.
function _init()
end

function _update()
end

function _draw()
  cls(0)
  print("hello gba", 8, 8, 7)
end
`
	if err := os.WriteFile(filepath.Join(tmp, GameFileName), []byte(game), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", GameFileName, err)
	}
	if err := os.Rename(tmp, projectDir); err != nil {
		return fmt.Errorf("finalize project: %w", err)
	}
	return nil
}
