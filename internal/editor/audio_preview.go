const (
	SFXPreviewSampleRate = 16_384
	// Looping previews are deliberately finite so a forgotten player cannot
	// retain an unbounded stream. Stop/replay remains immediate in the UI.
	SFXPreviewMaxSamples = 4 * SFXPreviewSampleRate
	// MusicPreviewMaxSamples caps cyclic/indefinite songs. Finite songs render
	// through their authored ending so the editor's Play button previews the
	// complete arrangement.
	MusicPreviewMaxSamples = 8 * SFXPreviewSampleRate
	MusicRenderMaxSamples  = 30 * 60 * SFXPreviewSampleRate
	// One second exceeds the fixed-point lifetime of the longest level-2
	// reverb plus dampen tail. Non-looping previews render this guard and trim
	// only trailing silence, so the visible/playable PCM includes every echo
	// without padding ordinary effects.
	sfxPreviewFilterTailGuard = SFXPreviewSampleRate
)

// SFXPreview is target-rate signed 8-bit mono generated by the exact runtime
// sequencer and mixer. Desktop playback adapts these bytes to the host output
// format only after this target PCM has been produced.
type SFXPreview struct {
	Samples      []int8
	EffectID     int
	Offset       int
	End          int
	SpeedSamples int
	SpeedUnits   int
	LoopStart    int
	LoopEnd      int
}

// SFXPlaybackPosition identifies the authored step sounding at one target-rate
// sample and the sample's fractional progress through that step. The editor
// uses this metadata for a smooth piano-roll playhead without changing the
// user's edit selection.
type SFXPlaybackPosition struct {
	Step                int
	StepSample          int
	StepDurationSamples int
}

func sfxPlaybackPositionAtSample(sample, speedUnits, offset, end, loopStart, loopEnd int) (SFXPlaybackPosition, bool) {
	if sample < 0 || speedUnits <= 0 || offset < 0 || end <= offset {
		return SFXPlaybackPosition{}, false
	}
	stepOrdinal := 0
	for audio.SFXSamplesForUnits(uint32(stepOrdinal+1)*uint32(speedUnits)) <= uint32(sample) {
		stepOrdinal++
	}
	step := offset + stepOrdinal
	if loopStart >= offset && loopEnd > loopStart && loopEnd <= end && step >= loopEnd {
		step = loopStart + (step-loopStart)%(loopEnd-loopStart)
	}
	if step < offset || step >= end {
		return SFXPlaybackPosition{}, false
	}
	start := int(audio.SFXSamplesForUnits(uint32(stepOrdinal) * uint32(speedUnits)))
	finish := int(audio.SFXSamplesForUnits(uint32(stepOrdinal+1) * uint32(speedUnits)))
	return SFXPlaybackPosition{
		Step:                step,
		StepSample:          sample - start,
		StepDurationSamples: max(1, finish-start),
	}, true
}

func (p *SFXPreview) StepAtSample(sample int) int {
	if p == nil || sample < 0 || sample >= len(p.Samples) || p.SpeedSamples <= 0 || p.SpeedUnits <= 0 {
		return -1
	}
	position, ok := sfxPlaybackPositionAtSample(sample, p.SpeedUnits, p.Offset, p.End, p.LoopStart, p.LoopEnd)
	if !ok {
		return -1
	}
	return position.Step
}

// SFXAssetPlaybackPosition maps music-pattern time to the step in one authored
// clip. Music starts assigned clips at each pattern boundary, matching the
// runtime sequencer.
func SFXAssetPlaybackPosition(effect assetsync.SFXAsset, sample int) (SFXPlaybackPosition, bool) {
	loopStart, loopEnd := -1, -1
	if effect.Loop != nil {
		loopStart, loopEnd = effect.Loop.Start, effect.Loop.End
	}
	return sfxPlaybackPositionAtSample(sample, effect.Speed, 0, len(effect.Steps), loopStart, loopEnd)
}

