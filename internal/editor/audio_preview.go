func previewRuntimeSFX(library assetsync.SFXLibrary) ([]audio.SFXDefinition, []audio.SFXStep, error) {
	targetDefinitions, targetSteps, err := assetsync.CompileSFX(library)
	if err != nil {
		return nil, nil, err
	}
	definitions := make([]audio.SFXDefinition, len(targetDefinitions))
	for index, definition := range targetDefinitions {
		definitions[index] = audio.SFXDefinition{
			StepOffset: definition.StepOffset, ID: definition.ID, Speed: definition.Speed,
			StepCount: definition.StepCount, LoopStart: definition.LoopStart, LoopEnd: definition.LoopEnd,
			Filters: audio.SFXFilter(definition.Filters),
		}
	}
	steps := make([]audio.SFXStep, len(targetSteps))
	for index, step := range targetSteps {
		kind, ok := previewSourceKind(step.Waveform)
		if !ok {
			return nil, nil, fmt.Errorf("SFX preview waveform %q is unsupported", step.Waveform)
		}
		effect, ok := previewSFXEffect(step.Effect)
		if !ok {
			return nil, nil, fmt.Errorf("SFX preview effect %q is unsupported", step.Effect)
		}
		steps[index] = audio.SFXStep{PhaseStep: step.PhaseStep, Volume: step.Volume, Kind: kind, Effect: effect}
	}
	return definitions, steps, nil
}

// RenderSFXPreview compiles the in-memory authored library and runs it through
// runtime/audio. Length zero means all remaining steps, matching sfx().
func RenderSFXPreview(library assetsync.SFXLibrary, id, offset, length int) (*SFXPreview, error) {
	return RenderSFXPreviewVolume(library, id, offset, length, assetsync.AudioMasterVolumeMax)
}

// RenderSFXPreviewVolume applies the persisted project master gain through the
// same sequencer setting generated cartridges use.
func RenderSFXPreviewVolume(library assetsync.SFXLibrary, id, offset, length, masterVolume int) (*SFXPreview, error) {
	definitions, steps, err := previewRuntimeSFX(library)
	if err != nil {
		return nil, err
	}
	definitionIndex := -1
	for index, definition := range definitions {
		if int(definition.ID) == id {
			definitionIndex = index
		}
	}
	if definitionIndex < 0 {
		return nil, fmt.Errorf("SFX id %d is not in the library", id)
	}
	definition := definitions[definitionIndex]
	end := int(definition.StepCount)
	if offset < 0 || offset >= end || length < 0 {
		return nil, fmt.Errorf("SFX %d preview range offset=%d length=%d is invalid for %d steps", id, offset, length, end)
	}
	if length > 0 {
		end = offset + length
		if end > int(definition.StepCount) {
			return nil, fmt.Errorf("SFX %d preview range [%d,%d) exceeds %d steps", id, offset, end, definition.StepCount)
		}
	}
	loopStart, loopEnd := -1, -1
	if definition.LoopStart != audio.NoSFXLoop && int(definition.LoopStart) >= offset && int(definition.LoopEnd) <= end {
		loopStart, loopEnd = int(definition.LoopStart), int(definition.LoopEnd)
	}
	speedSamples := int(audio.SFXSamplesForUnits(uint32(definition.Speed)))
	authoredSampleN := int(audio.SFXSamplesForUnits(uint32((end - offset) * int(definition.Speed))))
	sampleN := authoredSampleN
	if loopStart >= 0 {
		sampleN = SFXPreviewMaxSamples
	} else {
		tailGuard := audio.SFXEdgeSamples
		if definition.Filters.Reverb() != 0 || definition.Filters.Dampen() != 0 {
			tailGuard = sfxPreviewFilterTailGuard
		}
		sampleN += tailGuard
	}

	var mixer audio.Mixer
	if !mixer.Init(audio.SFXMixerVoices) {
		return nil, fmt.Errorf("initialize SFX preview mixer")
	}
	var player audio.SFXPlayer
	if !player.Init(&mixer, definitions, steps) || masterVolume < 0 || masterVolume > assetsync.AudioMasterVolumeMax ||
		!player.SetMasterVolume(uint16(masterVolume)) {
		return nil, fmt.Errorf("initialize SFX preview player")
	}
	if _, ok := player.Play(id, 0, offset, length); !ok {
		return nil, fmt.Errorf("start SFX %d preview", id)
	}
	samples := make([]int8, sampleN)
	player.MixMono(samples)
	if sampleN > authoredSampleN && loopStart < 0 {
		endSample := len(samples)
		for endSample > authoredSampleN && samples[endSample-1] == 0 {
			endSample--
		}
		samples = samples[:endSample]
	}
	return &SFXPreview{
		Samples: samples, EffectID: id, Offset: offset, End: end,
		SpeedSamples: speedSamples, SpeedUnits: int(definition.Speed), LoopStart: loopStart, LoopEnd: loopEnd,
	}, nil
}

type MusicPreviewSegment struct {
	PatternID   int
	StartSample int
	EndSample   int
}

// MusicPreview is a bounded target-rate rendering of one pattern entry point.
// Segments describe the exact pattern active over each half-open sample range.
type MusicPreview struct {
	Samples  []int8
	Segments []MusicPreviewSegment
	EntryID  int
	MuteMask uint8
	FadeMS   int
}

// SamplePreview keeps source and target views separate. SourceSamples and
// SourcePlayback are the version-1 mono downmix; the channel-specific fields
// retain a stereo WAV for source display and audition only. TargetSamples are
// rendered through runtime/audio with authored gain and loop semantics, while
// TargetROM is the exact converted mono ROM range.
type SamplePreview struct {
	SourceRate          int
	SourceChannels      int
	SourceSamples       []int8
	SourceLeftSamples   []int8
	SourceRightSamples  []int8
	SourcePlayback      []int8
	SourcePlaybackLeft  []int8
	SourcePlaybackRight []int8
	TargetSamples       []int8
	TargetROM           []int8
	LoopStart           uint32
	LoopEnd             uint32
	Loop                bool
}

// RenderSamplePreview runs target PCM through the same fixed mixer used by a
// generated cartridge. One converted sample-length is rendered, so looping
// assets expose their loop behavior without creating an unbounded preview.
func RenderSamplePreview(projectDir string, sample assetsync.SampleAsset) (*SamplePreview, error) {
	return RenderSamplePreviewVolume(projectDir, sample, assetsync.AudioMasterVolumeMax)
}

// RenderSamplePreviewVolume applies the persisted project master gain to the
// exact converted target bytes without changing source audition data.
func RenderSamplePreviewVolume(projectDir string, sample assetsync.SampleAsset, masterVolume int) (*SamplePreview, error) {
	conversion, err := assetsync.PreviewSampleConversion(projectDir, sample)
	if err != nil {
		return nil, err
	}
	definition := conversion.Definition
	var mixer audio.Mixer
	if !mixer.Init(audio.SFXSampleMixerVoices) {
		return nil, fmt.Errorf("initialize sample preview mixer")
	}
	var player audio.SFXPlayer
	if !player.Init(&mixer, nil, nil) || masterVolume < 0 || masterVolume > assetsync.AudioMasterVolumeMax ||
		!player.SetMasterVolume(uint16(masterVolume)) || !player.InitSamples([]audio.SampleDefinition{{
		DataOffset: 0, DataLength: definition.DataLength,
		LoopStart: definition.LoopStart, LoopEnd: definition.LoopEnd,
		Volume: definition.Volume, ID: definition.ID, Priority: definition.Priority, Loop: definition.Loop,
	}}, conversion.TargetPCM) {
		return nil, fmt.Errorf("initialize sample preview player")
	}
	if !player.Sample(int(definition.ID), -1, -1) {
		return nil, fmt.Errorf("start sample %d preview", definition.ID)
	}
	target := make([]int8, len(conversion.TargetPCM))
	player.MixMono(target)
	return &SamplePreview{
		SourceRate:          conversion.SourceRate,
		SourceChannels:      conversion.SourceChannels,
		SourceSamples:       slices.Clone(conversion.SourcePCM),
		SourceLeftSamples:   slices.Clone(conversion.SourceLeftPCM),
		SourceRightSamples:  slices.Clone(conversion.SourceRightPCM),
		SourcePlayback:      slices.Clone(conversion.SourcePlaybackPCM),
		SourcePlaybackLeft:  slices.Clone(conversion.SourcePlaybackLeftPCM),
		SourcePlaybackRight: slices.Clone(conversion.SourcePlaybackRightPCM),
		TargetSamples:       target,
		TargetROM:           slices.Clone(conversion.TargetPCM),
		LoopStart:           definition.LoopStart,
		LoopEnd:             definition.LoopEnd,
		Loop:                definition.Loop,
	}, nil
}

func (p *MusicPreview) PatternAtSample(sample int) int {
	segment, ok := p.SegmentAtSample(sample)
	if !ok {
		return -1
	}
	return segment.PatternID
}

// SegmentAtSample returns the exact active pattern span so UI consumers can
// derive both the pattern ID and pattern-local playback time.
func (p *MusicPreview) SegmentAtSample(sample int) (MusicPreviewSegment, bool) {
	if p == nil || sample < 0 || sample >= len(p.Samples) {
		return MusicPreviewSegment{}, false
	}
	for _, segment := range p.Segments {
		if sample >= segment.StartSample && sample < segment.EndSample {
			return segment, true
		}
	}
	return MusicPreviewSegment{}, false
}

func musicPreviewTimelineLimit(patterns []assetsync.TargetMusicPattern, entryID, maxSamples int) ([]MusicPreviewSegment, int, error) {
	byID := make(map[int]assetsync.TargetMusicPattern, len(patterns))
	for _, pattern := range patterns {
		byID[int(pattern.ID)] = pattern
	}
	current, exists := byID[entryID]
	if !exists {
		return nil, 0, fmt.Errorf("music pattern id %d is not in the library", entryID)
	}
	segments := make([]MusicPreviewSegment, 0, 16)
	sample := 0
	for sample < maxSamples {
		end := maxSamples
		if current.DurationSamples != 0 {
			end = sample + int(current.DurationSamples)
		}
		if end > maxSamples {
			end = maxSamples
		}
		segments = append(segments, MusicPreviewSegment{PatternID: int(current.ID), StartSample: sample, EndSample: end})
		sample = end
		if sample >= maxSamples || current.Next == assetsync.MusicStopPattern {
			break
		}
		current = byID[int(current.Next)]
	}
	return segments, sample, nil
}

// musicPreviewSampleLimit returns the complete duration for an arrangement
// that reaches an authored stop. Cyclic and indefinite graphs retain the short
// interactive cap, while abnormally long finite graphs retain the renderer's
// hard memory ceiling.
func musicPreviewSampleLimit(patterns []assetsync.TargetMusicPattern, entryID int) (int, error) {
	byID := make(map[int]assetsync.TargetMusicPattern, len(patterns))
	for _, pattern := range patterns {
		byID[int(pattern.ID)] = pattern
	}
	current, exists := byID[entryID]
	if !exists {
		return 0, fmt.Errorf("music pattern id %d is not in the library", entryID)
	}
	seen := make(map[int]bool, len(patterns))
	var samples uint64
	for {
		id := int(current.ID)
		if seen[id] || current.DurationSamples == 0 {
			return MusicPreviewMaxSamples, nil
		}
		seen[id] = true
		samples += uint64(current.DurationSamples)
		if samples >= MusicRenderMaxSamples {
			return MusicRenderMaxSamples, nil
		}
		if current.Next == assetsync.MusicStopPattern {
			return int(samples), nil
		}
		next, ok := byID[int(current.Next)]
		if !ok {
			return 0, fmt.Errorf("music pattern %d points to missing pattern %d", current.ID, current.Next)
		}
		current = next
	}
}

// RenderMusicPreview compiles both authored libraries and runs the exact
// target music/SFX sequencer. MuteMask is host transport state only; clearing
// channel assignments after compilation preserves target pattern timing.
func RenderMusicPreview(sfx assetsync.SFXLibrary, music assetsync.MusicLibrary, entryID int, muteMask uint8) (*MusicPreview, error) {
	return RenderMusicPreviewFadeVolume(sfx, music, entryID, muteMask, 0, assetsync.AudioMasterVolumeMax)
}

// RenderMusicPreviewFade is the call-site fade variant used by host tests and
// tools. Fade duration is transient music() transport state, not pattern asset
// data, so the native editor's ordinary Play button deliberately passes zero.
func RenderMusicPreviewFade(sfx assetsync.SFXLibrary, music assetsync.MusicLibrary, entryID int, muteMask uint8, fadeMS int) (*MusicPreview, error) {
	return RenderMusicPreviewFadeVolume(sfx, music, entryID, muteMask, fadeMS, assetsync.AudioMasterVolumeMax)
}

// RenderMusicPreviewVolume is the ordinary no-call-site-fade project preview
// with persisted master gain.
func RenderMusicPreviewVolume(sfx assetsync.SFXLibrary, music assetsync.MusicLibrary, entryID int, muteMask uint8, masterVolume int) (*MusicPreview, error) {
	return RenderMusicPreviewFadeVolume(sfx, music, entryID, muteMask, 0, masterVolume)
}

// RenderMusicPreviewFadeVolume combines transient call-site fade state with
// the persisted project master gain.
func RenderMusicPreviewFadeVolume(sfx assetsync.SFXLibrary, music assetsync.MusicLibrary, entryID int, muteMask uint8, fadeMS, masterVolume int) (*MusicPreview, error) {
	patterns, err := assetsync.CompileMusic(music, sfx)
	if err != nil {
		return nil, err
	}
	limit, err := musicPreviewSampleLimit(patterns, entryID)
	if err != nil {
		return nil, err
	}
	return renderMusicPreviewLimit(sfx, music, entryID, muteMask, fadeMS, masterVolume, limit)
}

// RenderMusicPreviewLimit runs the same target sequencer as the editor preview
// with an explicit upper bound. Corpus/export tooling can therefore render a
// complete stopping song while the interactive editor retains its short loop
// cap. The hard ceiling prevents malformed cyclic graphs from allocating an
// unbounded host buffer.
func RenderMusicPreviewLimit(sfx assetsync.SFXLibrary, music assetsync.MusicLibrary, entryID int, muteMask uint8, maxSamples int) (*MusicPreview, error) {
	return renderMusicPreviewLimitMode(sfx, music, entryID, muteMask, 0, assetsync.AudioMasterVolumeMax, maxSamples, false)
}

func renderMusicPreviewLimit(sfx assetsync.SFXLibrary, music assetsync.MusicLibrary, entryID int, muteMask uint8, fadeMS, masterVolume, maxSamples int) (*MusicPreview, error) {
	return renderMusicPreviewLimitMode(sfx, music, entryID, muteMask, fadeMS, masterVolume, maxSamples, false)
}

// RenderMusicPreviewWordsLimit is the packed FIFO-word equivalent used to
// verify target stream rendering against the byte-oriented host preview.
func RenderMusicPreviewWordsLimit(sfx assetsync.SFXLibrary, music assetsync.MusicLibrary, entryID int, muteMask uint8, maxSamples int) (*MusicPreview, error) {
	return renderMusicPreviewLimitMode(sfx, music, entryID, muteMask, 0, assetsync.AudioMasterVolumeMax, maxSamples, true)
}

func renderMusicPreviewLimitMode(sfx assetsync.SFXLibrary, music assetsync.MusicLibrary, entryID int, muteMask uint8, fadeMS, masterVolume, maxSamples int, packed bool) (*MusicPreview, error) {
	if maxSamples <= 0 || maxSamples > MusicRenderMaxSamples {
		return nil, fmt.Errorf("music render limit %d is outside 1..%d samples", maxSamples, MusicRenderMaxSamples)
	}
	definitions, steps, err := previewRuntimeSFX(sfx)
	if err != nil {
		return nil, err
	}
	targetPatterns, err := assetsync.CompileMusic(music, sfx)
	if err != nil {
		return nil, err
	}
	segments, sampleN, err := musicPreviewTimelineLimit(targetPatterns, entryID, maxSamples)
	if err != nil {
		return nil, err
	}
	patterns := make([]audio.MusicPattern, len(targetPatterns))
	for index, pattern := range targetPatterns {
		channels := pattern.Channels
		for channel := range channels {
			if muteMask&(1<<channel) != 0 {
				channels[channel] = -1
			}
		}
		patterns[index] = audio.MusicPattern{
			DurationSamples: pattern.DurationSamples, Channels: channels,
			ID: pattern.ID, Next: pattern.Next,
		}
	}

	var mixer audio.Mixer
	if !mixer.Init(audio.SFXMixerVoices) {
		return nil, fmt.Errorf("initialize music preview mixer")
	}
	var player audio.SFXPlayer
	if !player.Init(&mixer, definitions, steps) || masterVolume < 0 || masterVolume > assetsync.AudioMasterVolumeMax ||
		!player.SetMasterVolume(uint16(masterVolume)) || !player.InitMusic(patterns) {
		return nil, fmt.Errorf("initialize music preview player")
	}
	if !player.Music(entryID, fadeMS) {
		return nil, fmt.Errorf("start music pattern %d preview with %d ms fade", entryID, fadeMS)
	}
	samples := make([]int8, sampleN)
	if packed {
		words := make([]uint32, (sampleN+3)/4)
		player.MixMonoWords(words)
		for sample := range samples {
			samples[sample] = int8(uint8(words[sample/4] >> (8 * (sample & 3))))
		}
	} else {
		player.MixMono(samples)
	}
	return &MusicPreview{Samples: samples, Segments: segments, EntryID: entryID, MuteMask: muteMask, FadeMS: fadeMS}, nil
}
