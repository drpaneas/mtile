// GenerateGo flattens a project and emits the declarations expected by the
// generated game package. ROM data is initialized; all RAM objects are
// zero-valued .ewram globals and are wired only by InitAssets.
func GenerateGo(projectDir, packageName string) ([]byte, error) {
	if packageName == "" {
		packageName = "main"
	}
	if !validPackageName(packageName) {
		return nil, fmt.Errorf("invalid generated package name %q", packageName)
	}
	assets, err := Load(projectDir)
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	b.WriteString("// Code generated by mtile assetsync. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	b.WriteString("import (\n")
	b.WriteString("\t_ \"unsafe\" // required for //go:section\n")
	b.WriteString("\n")
	b.WriteString("\trt \"github.com/drpaneas/mtile/runtime\"\n")
	nativeAudioEnabled := assets.NativeAudio != nil && (len(assets.NativeAudio.Library.Sounds) != 0 ||
		len(assets.NativeAudio.Library.Clips) != 0 || len(assets.NativeAudio.Library.Parts) != 0 || len(assets.NativeAudio.Library.Songs) != 0)
	if nativeAudioEnabled {
		b.WriteString("\t\"github.com/drpaneas/mtile/runtime/audio\"\n")
	}
	if nativeAudioEnabled {
		b.WriteString("\t\"github.com/drpaneas/mtile/runtime/hw\"\n")
	}
	b.WriteString(")\n\n")
	mapPlaneMask := uint8((1 << uint(assets.MapLayers)) - 1)
	fmt.Fprintf(&b, "const (\n\tSheetW = %d\n\tSheetH = %d\n\tSpriteCols = %d\n\tSpriteRows = %d\n\tSpriteN = %d\n\tMapW = %d\n\tMapH = %d\n\tMapLayers = %d\n\tMapPlaneMask = %d\n\tMapStreaming = %t\n)\n\n", assets.SheetW, assets.SheetH, assets.SpriteCols, assets.SpriteRows, assets.SpriteN, assets.MapW, assets.MapH, assets.MapLayers, mapPlaneMask, assets.MapStreaming)

	b.WriteString("//go:section .rodata\n")
	writeByteArray(&b, "sheetROM", assets.SheetROM)
	b.WriteString("//go:section .rodata\n")
	writeUint16Array(&b, "mapROM", assets.MapROM)
	b.WriteString("//go:section .rodata\n")
	writeByteArray(&b, "flagROM", assets.FlagROM)
	b.WriteString("//go:section .rodata\n")
	writeUint16Array(&b, "paletteROM", assets.PaletteROM[:])
	b.WriteString("//go:section .rodata\n")
	writePoseIndexArray(&b, assets.PoseIndex)
	b.WriteString("//go:section .rodata\n")
	writePosePartArray(&b, assets.PoseParts)
	writeAnimationArrays(&b, assets)
	if assets.ObjSpriteN > 0 {
		compact, index := CompactObjectSheetCells(assets.ObjSheetROM, assets.ObjSheetW, assets.ObjSpriteN)
		fmt.Fprintf(&b, "const (\n\tObjSheetW = %d\n\tObjSheetH = %d\n\tObjSpriteCols = %d\n\tObjSpriteRows = %d\n\tObjSpriteN = %d\n)\n\n",
			assets.ObjSheetW, assets.ObjSheetH, assets.ObjSpriteCols, assets.ObjSpriteRows, assets.ObjSpriteN)
		b.WriteString(ObjectSheetROMDeclaration(compact))
		b.WriteString("//go:section .rodata\n")
		writeUint32Array(&b, "objSheetIndexROM", index)
	}

	if nativeAudioEnabled {
		writeNativeAudioArrays(&b, assets.NativeAudio.Library)
	}

	b.WriteString(FontGoDeclaration(assets.CompiledFont()))

	// Standalone assetsync output has no Lua AST from which to prove that
	// sset is unused, so preserve the fully mutable sheet contract. The main
	// transpiler can select ROM-backed immutable art automatically.
	b.WriteString("//go:section .ewram\n")
	fmt.Fprintf(&b, "var sheetRAM [%d]byte\n\n", len(assets.SheetROM))
	b.WriteString("//go:section .ewram\n")
	if assets.MapStreaming {
		b.WriteString("var mapRAM [rt.MapCacheCells]uint16\n\n")
		b.WriteString("//go:section .ewram\n")
		b.WriteString("var mapChunksRAM [rt.MapCacheSlots]rt.MapChunk\n\n")
		b.WriteString("//go:section .ewram\n")
		b.WriteString("var mapEditsRAM [rt.MapEditCapacity]rt.MapEdit\n\n")
	} else {
		fmt.Fprintf(&b, "var mapRAM [%d]uint16\n\n", len(assets.MapROM))
	}
	b.WriteString("//go:section .ewram\n")
	fmt.Fprintf(&b, "var flagRAM [%d]byte\n\n", len(assets.FlagROM))
	b.WriteString("//go:section .ewram\n")
	b.WriteString("var cartData rt.AssetMemory\n\n")

	b.WriteString(`// InitAssets wires zero-valued EWRAM arrays to the runtime and copies
// trusted ROM data into the RAM asset view. It also installs the project's
// complete 256-entry BGR555 palette.
func InitAssets(ctx *rt.Context) bool {
	if ctx == nil {
		return false
	}
	cartData.SheetW, cartData.SheetH = SheetW, SheetH
	cartData.SpriteCols, cartData.SpriteRows = SpriteCols, SpriteRows
	cartData.MapW, cartData.MapH, cartData.MapLayers, cartData.MapPlaneMask = MapW, MapH, MapLayers, MapPlaneMask
	cartData.SpriteN = SpriteN
	cartData.MapStreaming = MapStreaming
	cartData.Sheet = sheetRAM[:]
	cartData.Map = mapRAM[:]
	cartData.Flags = flagRAM[:]
	cartData.PoseIndex, cartData.PoseParts = poseIndexROM[:], posePartROM[:]
	cartData.AnimationClips, cartData.AnimationFrames = animationClipROM[:], animationFrameROM[:]
`)
	if assets.ObjSpriteN > 0 {
		b.WriteString("\tcartData.ObjSheetW, cartData.ObjSheetH = ObjSheetW, ObjSheetH\n")
		b.WriteString("\tcartData.ObjSpriteCols, cartData.ObjSpriteRows, cartData.ObjSpriteN = ObjSpriteCols, ObjSpriteRows, ObjSpriteN\n")
		b.WriteString("\tcartData.ObjSheet, cartData.ObjSheetIndex = objSheetROM.Pixels[:], objSheetIndexROM[:]\n")
	}
	if assets.MapStreaming {
		b.WriteString("\tcartData.MapChunks = mapChunksRAM[:]\n\tcartData.MapEdits = mapEditsRAM[:]\n")
	}
	b.WriteString(`	image := rt.AssetImage{
		SheetW: SheetW, SheetH: SheetH,
		SpriteCols: SpriteCols, SpriteRows: SpriteRows,
		MapW: MapW, MapH: MapH, MapLayers: MapLayers, MapPlaneMask: MapPlaneMask, SpriteN: SpriteN, MapStreaming: MapStreaming,
		Sheet: sheetROM[:], Map: mapROM[:], Flags: flagROM[:],
		PoseIndex: poseIndexROM[:], PoseParts: posePartROM[:],
		AnimationClips: animationClipROM[:], AnimationFrames: animationFrameROM[:],
`)
	if assets.ObjSpriteN > 0 {
		b.WriteString("\t\tObjSheetW: ObjSheetW, ObjSheetH: ObjSheetH, ObjSpriteCols: ObjSpriteCols, ObjSpriteRows: ObjSpriteRows, ObjSpriteN: ObjSpriteN,\n")
		b.WriteString("\t\tObjSheet: objSheetROM.Pixels[:], ObjSheetIndex: objSheetIndexROM[:],\n")
	}
	b.WriteString(`	}
	if !ctx.Init(&image, &cartData) {
		return false
	}
	ctx.LoadPalette(&paletteROM)
	return ctx.SetFont(&projectFontROM)
}
`)

	if nativeAudioEnabled {
		settings := assets.NativeAudio.Settings
		fmt.Fprintf(&b, `
// InitNativeAudio binds the strict four-channel PSG library. The caller starts
// the controller after game initialization and may queue music first.
func InitNativeAudio(controller *audio.Controller) bool {
	if controller == nil || !controller.Init(audio.ProfilePSG) ||
		!controller.ConfigureOutput(%d, %d, %s) {
		return false
	}
	return controller.Bind(audio.Library{
		Sounds: nativeSoundROM[:], Clips: nativeClipROM[:],
		Parts: nativePartROM[:], Songs: nativeSongROM[:],
	})
}
`, settings.LeftLevel, settings.RightLevel, nativePSGRatioGoName(settings.PSGRatio))
	}

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated assets: %w", err)
	}
	return formatted, nil
}

func nativePSGRatioGoName(ratio int) string {
	switch ratio {
	case 25:
		return "hw.PSGMix25"
	case 50:
		return "hw.PSGMix50"
	default:
		return "hw.PSGMix100"
	}
}

func nativeSoundKindGoName(kind audio.SoundKind) string {
	return [...]string{"audio.SoundCH1", "audio.SoundCH2", "audio.SoundCH3", "audio.SoundCH4"}[kind]
}

func nativeRouteGoName(route hw.SoundRoute) string {
	return [...]string{"hw.SoundRouteNone", "hw.SoundRouteRight", "hw.SoundRouteLeft", "hw.SoundRouteBoth"}[route]
}

func nativeEnvelopeDirectionGoName(direction hw.EnvelopeDirection) string {
	if direction == hw.EnvelopeUp {
		return "hw.EnvelopeUp"
	}
	return "hw.EnvelopeDown"
}

func nativeSweepDirectionGoName(direction hw.SweepDirection) string {
	if direction == hw.SweepDown {
		return "hw.SweepDown"
	}
	return "hw.SweepUp"
}

func writeNativeEnvelope(b *strings.Builder, envelope hw.HardwareEnvelope) {
	fmt.Fprintf(b, "hw.HardwareEnvelope{Initial: %d, Direction: %s, Pace: %d}",
		envelope.Initial, nativeEnvelopeDirectionGoName(envelope.Direction), envelope.Pace)
}

func writeNativePulse(b *strings.Builder, pulse hw.PulseConfig) {
	fmt.Fprintf(b, "hw.PulseConfig{Duty: hw.PulseDuty(%d), Length: %d, UseLength: %t, Envelope: ", pulse.Duty, pulse.Length, pulse.UseLength)
	writeNativeEnvelope(b, pulse.Envelope)
	fmt.Fprintf(b, ", Route: %s}", nativeRouteGoName(pulse.Route))
}

func writeNativeAudioArrays(b *strings.Builder, library audio.Library) {
	for index, sound := range library.Sounds {
		if len(sound.Macro.Steps) == 0 {
			continue
		}
		b.WriteString("//go:section .rodata\n")
		fmt.Fprintf(b, "var nativeSoundMacro%d = [%d]audio.SoundMacroStep{\n", index, len(sound.Macro.Steps))
		for _, step := range sound.Macro.Steps {
			fmt.Fprintf(b, "\t{PeriodDelta: %d, NoiseDivisor: %d, NoiseShift: %d, HasNoise: %t, NoiseNoteOffset: %d, HasNoiseNote: %t},\n", step.PeriodDelta, step.NoiseDivisor, step.NoiseShift, step.HasNoise, step.NoiseNoteOffset, step.HasNoiseNote)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("//go:section .rodata\n")
	fmt.Fprintf(b, "var nativeSoundROM = [%d]audio.Sound{\n", len(library.Sounds))
	for index, sound := range library.Sounds {
		fmt.Fprintf(b, "\t{ID: %d, Kind: %s, ", sound.ID, nativeSoundKindGoName(sound.Kind))
		switch sound.Kind {
		case audio.SoundCH1:
			b.WriteString("Pulse1: hw.Pulse1Config{Pulse: ")
			writeNativePulse(b, sound.Pulse1.Pulse)
			fmt.Fprintf(b, ", Sweep: hw.HardwareSweep{Pace: %d, Direction: %s, Shift: %d}}", sound.Pulse1.Sweep.Pace, nativeSweepDirectionGoName(sound.Pulse1.Sweep.Direction), sound.Pulse1.Sweep.Shift)
		case audio.SoundCH2:
			b.WriteString("Pulse2: ")
			writeNativePulse(b, sound.Pulse2)
		case audio.SoundCH3:
			fmt.Fprintf(b, "Wave: hw.WaveConfig{Wave: hw.Waveform{Length: %d, Samples: [64]uint8{", sound.Wave.Wave.Length)
			for _, sample := range sound.Wave.Wave.Samples {
				fmt.Fprintf(b, "%d,", sample)
			}
			fmt.Fprintf(b, "}}, Level: hw.WaveLevel(%d), StartBank: %d, Length: %d, UseLength: %t, Route: %s}", sound.Wave.Level, sound.Wave.StartBank, sound.Wave.Length, sound.Wave.UseLength, nativeRouteGoName(sound.Wave.Route))
		case audio.SoundCH4:
			fmt.Fprintf(b, "Noise: hw.NoiseConfig{Width: hw.NoiseWidth(%d), Divisor: %d, Shift: %d, Length: %d, UseLength: %t, Envelope: ", sound.Noise.Width, sound.Noise.Divisor, sound.Noise.Shift, sound.Noise.Length, sound.Noise.UseLength)
			writeNativeEnvelope(b, sound.Noise.Envelope)
			fmt.Fprintf(b, ", Route: %s}", nativeRouteGoName(sound.Noise.Route))
		}
		if len(sound.Macro.Steps) != 0 {
			fmt.Fprintf(b, ", Macro: audio.SoundMacro{Steps: nativeSoundMacro%d[:], LoopStart: %d}", index, sound.Macro.LoopStart)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")

	for index, clip := range library.Clips {
		b.WriteString("//go:section .rodata\n")
		fmt.Fprintf(b, "var nativeClipEvents%d = [%d]audio.NoteEvent{\n", index, len(clip.NoteEvents))
		for _, event := range clip.NoteEvents {
			fmt.Fprintf(b, "\t{Tick: %d, DurationTicks: %d, Note: %d, SoundID: %d, Priority: %d, Legato: %t},\n", event.Tick, event.DurationTicks, event.Note, event.SoundID, event.Priority, event.Legato)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("//go:section .rodata\n")
	fmt.Fprintf(b, "var nativeClipROM = [%d]audio.Clip{\n", len(library.Clips))
	for index, clip := range library.Clips {
		fmt.Fprintf(b, "\t{ID: %d, Kind: %s, LengthTicks: %d, NoteEvents: nativeClipEvents%d[:]},\n", clip.ID, nativeSoundKindGoName(clip.Kind), clip.LengthTicks, index)
	}
	b.WriteString("}\n\n")

	b.WriteString("//go:section .rodata\n")
	fmt.Fprintf(b, "var nativePartROM = [%d]audio.Part{\n", len(library.Parts))
	for _, part := range library.Parts {
		fmt.Fprintf(b, "\t{ID: %d, LengthTicks: %d, Tempo: %d, PSGClips: [4]int16{%d, %d, %d, %d}},\n", part.ID, part.LengthTicks, part.Tempo, part.PSGClips[0], part.PSGClips[1], part.PSGClips[2], part.PSGClips[3])
	}
	b.WriteString("}\n\n")

	for index, song := range library.Songs {
		b.WriteString("//go:section .rodata\n")
		fmt.Fprintf(b, "var nativeSongSequence%d = [%d]uint8{", index, len(song.Sequence))
		for _, partID := range song.Sequence {
			fmt.Fprintf(b, "%d,", partID)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("//go:section .rodata\n")
	fmt.Fprintf(b, "var nativeSongROM = [%d]audio.Song{\n", len(library.Songs))
	for index, song := range library.Songs {
		fmt.Fprintf(b, "\t{ID: %d, Tempo: %d, Sequence: nativeSongSequence%d[:], LoopStart: %d},\n", song.ID, song.Tempo, index, song.LoopStart)
	}
	b.WriteString("}\n\n")
}

// NativeAudioGoDeclarations emits allocation-free static CH1-CH4 records for
// the cartridge transpiler and standalone asset generator.
func NativeAudioGoDeclarations(library audio.Library) (string, error) {
	if !audio.ValidateLibrary(library) {
		return "", errors.New("native audio library failed runtime validation")
	}
	var b strings.Builder
	writeNativeAudioArrays(&b, library)
	return b.String(), nil
}

// GenerateFile writes generated asset code atomically to outputPath.
func GenerateFile(projectDir, outputPath, packageName string) error {
	source, err := GenerateGo(projectDir, packageName)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		return fmt.Errorf("create generated asset directory: %w", err)
	}
	tmp, err := os.CreateTemp(filepath.Dir(outputPath), ".assetsync-go-*")
	if err != nil {
		return fmt.Errorf("create generated asset file: %w", err)
	}
	tmpName := tmp.Name()
	defer func() { _ = os.Remove(tmpName) }()
	if err := tmp.Chmod(0o644); err != nil {
		_ = tmp.Close()
		return err
	}
	if _, err := tmp.Write(source); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("write generated asset file: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close generated asset file: %w", err)
	}
	if err := os.Rename(tmpName, outputPath); err != nil {
		return fmt.Errorf("replace generated asset file: %w", err)
	}
	return nil
}

func writeByteArray(b *strings.Builder, name string, values []byte) {
	fmt.Fprintf(b, "var %s = [%d]byte{\n", name, len(values))
	for i, value := range values {
		if i%16 == 0 {
			b.WriteString("\t")
		}
		fmt.Fprintf(b, "%s, ", strconv.Itoa(int(value)))
		if i%16 == 15 || i == len(values)-1 {
			b.WriteByte('\n')
		}
	}
	b.WriteString("}\n\n")
}

func writeUint16Array(b *strings.Builder, name string, values []uint16) {
	fmt.Fprintf(b, "var %s = [%d]uint16{\n", name, len(values))
	for i, value := range values {
		if i%12 == 0 {
			b.WriteString("\t")
		}
		fmt.Fprintf(b, "0x%04x, ", value)
		if i%12 == 11 || i == len(values)-1 {
			b.WriteByte('\n')
		}
	}
	b.WriteString("}\n\n")
}

func writeUint32Array(b *strings.Builder, name string, values []uint32) {
	fmt.Fprintf(b, "var %s = [%d]uint32{\n", name, len(values))
	for i, value := range values {
		if i%8 == 0 {
			b.WriteString("\t")
		}
		fmt.Fprintf(b, "0x%08x, ", value)
		if i%8 == 7 || i == len(values)-1 {
			b.WriteByte('\n')
		}
	}
	b.WriteString("}\n\n")
}

// writePoseIndexArray and writePosePartArray emit pspr's pose ROM tables.
// Poses are read-only cart metadata with no per-cart mutation path, so both
// stay in .rodata; an empty slice still yields a legal [0]rt.T{} array so
// poseIndexROM[:]/posePartROM[:] remain valid slice expressions.
func writePoseIndexArray(b *strings.Builder, values []FlatPose) {
	fmt.Fprintf(b, "var poseIndexROM = [%d]rt.PoseRange{\n", len(values))
	for _, v := range values {
		fmt.Fprintf(b, "\t{Start: %d, Count: %d, FlipOffsetX: %d, FlipOffsetY: %d},\n", v.Start, v.Count, v.FlipOffsetX, v.FlipOffsetY)
	}
	b.WriteString("}\n\n")
}

func writePosePartArray(b *strings.Builder, values []FlatPosePart) {
	fmt.Fprintf(b, "var posePartROM = [%d]rt.PosePart{\n", len(values))
	for _, v := range values {
		fmt.Fprintf(b, "\t{Tile: %d, X: %d, Y: %d, Flags: %d},\n", v.Tile, v.X, v.Y, v.Flags)
	}
	b.WriteString("}\n\n")
}

func validPackageName(name string) bool {
	if name == "" {
		return false
	}
	for i, r := range name {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_' || (i > 0 && r >= '0' && r <= '9') {
			continue
		}
		return false
	}
	return true
}
