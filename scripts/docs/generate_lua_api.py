#!/usr/bin/env python3
"""Keep the repository's detailed Lua guide in sync with the website API data."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs/lua-api.md"
CATEGORIES = {"input": "Input", "sprites": "Sprites and poses", "maps": "Maps", "drawing": "Drawing", "audio": "Audio", "math": "Math and bit operations", "data": "Tables and strings", "debug": "Time and diagnostics"}


def render():
    apis = json.loads((ROOT / "website/api.json").read_text())
    lines = ["# Lua API walkthrough", "", "<!-- Generated by scripts/docs/generate_lua_api.py; edit website/api.json. -->", "", "Every supported public builtin has a common call shape, explanation, and", "example below. Square brackets in signatures mark optional arguments; they", "are not Lua syntax. Examples are small fragments unless they define a whole", "callback, and asset-dependent examples require the named/numbered assets.", "", "Read the [language and project reference](reference.md) for the Lua subset,", "16:16 numbers, callbacks, source modules, and input mapping. The", "[renderer contract](render-modes.md) defines exact accepted Mode 0 call shapes", "and AUTO fallback conditions; a common signature here is not a promise that", "every argument expression can use Mode 0. Use the [four-channel audio API](audio/api-v2.md)", "for PSG music, or [import WAV and tracker songs](audio/samples.md) for Direct Sound.", "", "## Browse by task", ""]
    for category, title in CATEGORIES.items():
        lines.append(f"- [{title}](#{title.lower().replace(' ', '-')})")
    lines += [""]
    for category, title in CATEGORIES.items():
        lines += [f"## {title}", ""]
        for api in apis:
            if api["category"] != category:
                continue
            lines += [f"### {api['name']}", "", "```text", api["signature"], "```", "", api["summary"], "", api["note"], "", "```lua", api["example"], "```", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated guide is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            parser.exit(1, "docs/lua-api.md is stale; run python3 scripts/docs/generate_lua_api.py\n")
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
