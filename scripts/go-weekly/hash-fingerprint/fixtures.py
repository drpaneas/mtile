#!/usr/bin/env python3
"""Generate the predeclared 64-byte key fixtures; does not measure candidates."""
from pathlib import Path
import hashlib
import json

root = Path(__file__).resolve().parents[3]
prefix = "mtile/" + "x" * 50
suffixes = {
    "collision": "00000018 00000021 0000002a 00000047 00000054 0000005d 00000083 0000008c 00000090 000000b1 000000ba 000000d7 00000102 0000010b 00000115 0000011e",
    "distributed": "00000018 00000000 00000027 00000019 00000007 00000026 00000009 00000006 00000003 00000008 00000005 00000002 00000025 00000004 00000001 00000024",
    "same-tag": "000011d5 0000154a 00001b73 000036fb 00004696 00006250 0000665d 0000726b 0000ab73 00012e23 00012eb3 0001309d 000135df 00014774 000156be 000177f6",
}
body = """
slots = {}
queries = {}
absent = {}
tick = 0
generation = 0
checksum = 0
weighted = 0
misses = 0
errors = 0

function _init()
  for i = 1, 12 do
    local text = sourcekeys[i]
    local stored = sub(text, 1, #text)
    slots[stored] = i
    add(queries, sub(text, 1, #text))
  end
  for i = 13, 16 do
    local text = sourcekeys[i]
    add(absent, sub(text, 1, #text))
  end
end

function _update()
  tick += 1
  checksum = 0
  weighted = 0
  misses = 0
  local group = (tick - 1) % 3
  if group == 0 then generation += 1 end
  for i = group + 1, 12, 3 do
    local key = queries[i]
    local value = slots[key]
    if value != i + generation - 1 then errors += 1 end
    value += 1
    slots[key] = value
    checksum += value
    weighted += i * value
  end
  local missing = (tick - 1) % 4 + 1
  if slots[absent[missing]] == nil then misses += 1 else errors += 1 end
  if errors > 0 then pal(0, 8) end
end

function _draw()
  cls(0)
  spr(1, checksum % 232, 60)
end
"""
metadata = {"hashCapacity": 16, "storedKeys": 12, "absentKeys": 4, "keyBytes": 64,
            "hitsPerTick": 4, "updatesPerTick": 4, "missesPerTick": 1, "fullSweepEveryTicks": 3,
            "calibration": "Original 12-hit/12-update/4-miss baseline required 1,001,563 cycles and missed every tick; reduced before any candidate native capture.", "fixtures": {}}
for kind, suffix in suffixes.items():
    keys = [prefix + s for s in suffix.split()]
    source = "-- Generated by scripts/go-weekly/hash-fingerprint/fixtures.py\n"
    source += "sourcekeys = {\n" + ",\n".join("  " + json.dumps(k) for k in keys) + "\n}\n" + body
    path = root / "cmd/renderbench/testdata/workloads" / ("hash_fingerprint_" + kind.replace("-", "_") + ".lua")
    path.write_text(source)
    metadata["fixtures"][kind] = {"keys": keys, "sourceSHA256": hashlib.sha256(source.encode()).hexdigest()}
out = root / "docs/benchmarks/go-weekly/hash-fingerprint"
out.mkdir(parents=True, exist_ok=True)
(out / "workloads.json").write_text(json.dumps(metadata, indent=2) + "\n")
